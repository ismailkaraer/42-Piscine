int	ft_iterative_factorial(int nb)
{
	int	fact;
	int	i;

	if (nb == 0)
		return (1);
	if (nb < 0)
		return (0);
	i = 1;
	fact = 1;
	while (i <= nb)
	{
		fact *= i;
		i++;
	}
	return (fact);
}
